// ponytail: قوالب العقود — النقط "………" في النص هي الحقول.
// عند التعبئة بنستبدل كل كتلة نقط بالمدخل؛ اللي يفضل فاضي يفضل نقط زي ما هو.
// القوالب في DB (entity "templates")، وهنا القوالب الافتراضية اللي بتتزرع لو مفيش.
import type { TemplateData } from "@/types";

const DOTS = /(?:\.{3,}|…{2,}|\u2026{2,}|\.\s*){1,}/g;

// يفصل النص لمقاطع (نص / نقط) عشان الفورم.
export function splitDots(body: string) {
  const parts: { kind: "text" | "dot"; value: string }[] = [];
  let last = 0;
  for (const m of Array.from(body.matchAll(DOTS))) {
    if (m.index! > last) parts.push({ kind: "text", value: body.slice(last, m.index) });
    parts.push({ kind: "dot", value: m[0] });
    last = m.index! + m[0].length;
  }
  if (last < body.length || parts.length === 0) parts.push({ kind: "text", value: body.slice(last) });
  return parts;
}

// يركّب القالب: يستبدل كل كتلة نقط بالقيمة المقابلة (أو يبقيها نقط لو فاضية).
export function fillTemplate(body: string, values: string[]) {
  let i = 0;
  return body.replace(DOTS, () => values[i++]?.trim() || "");
}

